"""Make a ~2 minute Tamil test clip (call-centre style talk, short pauses) and its reference text."""
import subprocess, sys
from gtts import gTTS

LINES = [
    "வணக்கம், வாடிக்கையாளர் சேவை மையத்திலிருந்து பேசுகிறேன். உங்களுக்கு என்ன உதவி வேண்டும்?",
    "என் ஆர்டர் இன்னும் வரவில்லை. மூன்று நாட்களுக்கு முன்பே பணம் செலுத்திவிட்டேன்.",
    "ஒரு நிமிடம், உங்கள் ஆர்டர் எண்ணை சொல்லுங்கள். நான் உடனே சரிபார்க்கிறேன்.",
    "உங்கள் பொருள் இன்று மதியம் மூன்று மணிக்குள் வீட்டுக்கு வந்து சேரும்.",
    "பார்சலில் கண்ணாடி உடைந்து வந்திருக்கிறது. அதற்கு மாற்று பொருள் வேண்டும்.",
    "சரி, புகைப்படத்தை அனுப்புங்கள். நாளை காலை பத்து மணிக்கு எடுத்துச் செல்ல ஆள் வருவார்.",
    "என் கணக்கிலிருந்து பணம் எடுக்கப்பட்டது, ஆனால் ஆர்டர் உறுதியாகவில்லை.",
    "கவலைப்பட வேண்டாம், அந்த பணம் ஐந்து முதல் ஏழு நாட்களில் உங்கள் வங்கி கணக்கிற்கு திரும்ப வந்துவிடும்.",
    "இந்த மாதம் ஐநூறு ரூபாய்க்கு மேல் வாங்கினால் பத்து சதவீதம் தள்ளுபடி கிடைக்கும்.",
    "வேறு ஏதாவது உதவி தேவைப்பட்டால் எங்களை மீண்டும் அழைக்கவும். நன்றி, இனிய நாள்.",
    "நேற்று இரவு பெய்த கனமழையால் சாலைகளில் தண்ணீர் தேங்கியிருந்தது.",
    "அதனால் டெலிவரி வண்டிகள் தாமதமாக புறப்பட்டன. மன்னிக்கவும்.",
]
out = sys.argv[1]
parts = []
for i, line in enumerate(LINES):
    gTTS(line, lang="ta").save(f"/tmp/line{i}.mp3")
    parts += ["-i", f"/tmp/line{i}.mp3"]
# Join with 0.4 s gaps (normal speaking pauses), as one 16 kHz file.
n = len(LINES)
filt = "".join(f"[{i}:a]aresample=16000,apad=pad_dur=0.4[a{i}];" for i in range(n))
filt += "".join(f"[a{i}]" for i in range(n)) + f"concat=n={n}:v=0:a=1[out]"
subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *parts, "-filter_complex", filt, "-map", "[out]", "-ac", "1", out], check=True)
open(out + ".txt", "w").write(" ".join(LINES))
